-- schema.sql — โครงสร้างฐานข้อมูล (Supabase / PostgreSQL) ของทั้งระบบ
-- มี 3 ตาราง: users (บัญชีผู้ใช้) • trades (เทรดแต่ละออเดอร์) • notification_settings
-- (การตั้งค่าแจ้งเตือนรายคน)
-- พร้อมฟังก์ชัน delete_user_cascade (ลบบัญชีแบบปลอดภัย) และการเปิด RLS
-- (กันการเข้าถึงข้อมูลโดยตรง)
-- วิธีใช้: รันทั้งไฟล์ตั้งแต่บนลงล่างใน SQL Editor ของโปรเจกต์ที่ว่าง —
-- ไฟล์เรียงตามประวัติการแก้ไขโครงสร้างของระบบ
-- Run in the Supabase SQL editor, top to bottom, on an EMPTY project to build
-- the whole schema. The file reads as the migration history: the original
-- `trades` table first, then every change made to it afterwards.

-- The original table: one row per MT5 event, later extended below to one row
-- per position (position_id, close_price, tp, sl, status, closed_at) and tied
-- to a user (user_id).
-- [ตาราง trades] เก็บเทรด 1 ออเดอร์ต่อ 1 แถว: action (buy/sell), symbol, price, pnl
-- (กำไร/ขาดทุน), lot, timestamp (เวลาที่บันทึก)
-- คอลัมน์ position_id, close_price, tp, sl, status, closed_at, user_id
-- จะถูกเพิ่มภายหลังด้านล่าง
create table if not exists trades (
  id bigint generated by default as identity primary key,
  action text not null,
  symbol text not null,
  price numeric,
  pnl numeric,
  lot numeric,
  timestamp timestamptz default now()
);

-- Run once to add multi-tenant support.

-- [ตาราง users] บัญชีผู้ใช้: id, name, telegram_chat_id และ webhook_secret (รหัสที่ EA
-- ใช้บอกว่าข้อมูลเป็นของใคร ห้ามซ้ำ)
-- คอลัมน์อีเมล รหัสผ่าน role ฯลฯ จะถูกเพิ่มภายหลังด้านล่าง
create table users (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  telegram_chat_id text not null,
  webhook_secret text not null unique,
  created_at timestamptz not null default now()
);

-- ผูกทุกเทรดเข้ากับเจ้าของ (user_id → users.id)
-- ทำให้ผู้ใช้หลายคนใช้ระบบเดียวกันโดยข้อมูลไม่ปนกัน (multi-tenant)
alter table trades add column user_id uuid references users(id);

-- Backfill: insert a row for the existing owner using the current
-- TELEGRAM_CHAT_ID / WEBHOOK_SECRET env values, then set user_id on
-- existing trades to that row's id, e.g.:
--
-- insert into users (name, telegram_chat_id, webhook_secret)
-- values ('owner', '<TELEGRAM_CHAT_ID>', '<WEBHOOK_SECRET>')
-- returning id;
--
-- update trades set user_id = '<id from above>' where user_id is null;

-- Run once to move `trades` from "one row per event" to "one row per
-- position, updated on close" so a trade's open+close+TP/SL can be shown
-- together (needed for the frontend's trade-history table).
-- [สรุป] เพิ่ม position_id (เลขออเดอร์ของ MT5) เปลี่ยนจาก "1 แถวต่อ 1 เหตุการณ์" เป็น "1 แถวต่อ
-- 1 ออเดอร์":
-- ตอนเปิดเพิ่มแถว status = open, ตอนปิดอัปเดตแถวเดิม (close_price, pnl, status = closed,
-- closed_at)
alter table trades add column position_id bigint;
alter table trades add column close_price numeric;
alter table trades add column tp numeric;
alter table trades add column sl numeric;
alter table trades add column status text default 'open';
alter table trades add column closed_at timestamptz;

