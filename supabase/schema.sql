-- Emails are unique ignoring case: the original `unique (email)` constraint
-- is case-sensitive, so "A@x.com" and "a@x.com" could both exist and break
-- login lookup. Check for existing clashes first (must return no rows):
--   select lower(email), count(*) from users
--   where email is not null group by 1 having count(*) > 1;
-- ทำให้อีเมลไม่ซ้ำ "โดยไม่สนตัวพิมพ์เล็กใหญ่" ด้วย unique index บน lower(email)
create unique index if not exists users_email_lower_key on users (lower(email));

-- Per-user notification preferences (src/notification-settings.js).
-- Columns mirror the table currently in Supabase.
-- [ตาราง notification_settings] การตั้งค่าแจ้งเตือนของผู้ใช้แต่ละคน (1 แถวต่อ 1 คน เพราะ
-- user_id ห้ามซ้ำ)
-- มีสวิตช์เปิด/ปิดแต่ละแบบ กำไรขั้นต่ำ เกณฑ์ Drawdown และรายชื่อคู่เงินที่เลือก
create table if not exists notification_settings (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references users(id),
  enabled boolean not null default true,
  notify_buy boolean not null default true,
  notify_sell boolean not null default true,
  notify_tp boolean not null default true,
  notify_sl boolean not null default true,
  notify_close boolean not null default true,
  notify_risk boolean not null default true,
  notify_daily_summary boolean not null default true,
  notify_weekly_summary boolean not null default false,
  min_pnl numeric,
  max_drawdown numeric,
  symbols text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Deleting an account must remove its trades + settings + the user row
-- atomically (the admin page's delete button calls this via supabase.rpc).
-- A plpgsql function runs as one transaction, so a failure rolls everything back.
-- Only the server (service_role) may call it.
-- [ฟังก์ชัน] ลบบัญชีพร้อมเทรดและการตั้งค่าเป็น transaction เดียว (ลบครบทั้งหมดหรือไม่ลบเลย)
-- security definer = รันด้วยสิทธิ์เจ้าของฟังก์ชัน จึงต้องจำกัดผู้เรียกให้เหลือเฉพาะ
-- service_role ตามด้านล่าง
create or replace function delete_user_cascade(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from trades                where user_id = p_user_id;
  delete from notification_settings where user_id = p_user_id;
  delete from users                 where id      = p_user_id;
  if not found then
    raise exception 'user % not found', p_user_id;
  end if;
end $$;

-- ปิดสิทธิ์เรียกฟังก์ชันนี้จากทุกคน แล้วเปิดให้เฉพาะ service_role (คือเซิร์ฟเวอร์ของเรา)
revoke all on function delete_user_cascade(uuid) from public, anon, authenticated;
grant execute on function delete_user_cascade(uuid) to service_role;

-- Row Level Security: enabled with NO policies, so the public anon key can
-- read/write nothing. The Node server uses the service_role key
-- (SUPABASE_SERVICE_KEY), which bypasses RLS. The browser never talks to
-- Supabase directly — it only calls the Node API.
-- [สรุป] เปิด RLS ทุกตารางโดยไม่ตั้ง policy → anon key (ที่ใครก็ดูได้ในเว็บ)
-- อ่าน/เขียนอะไรไม่ได้เลย
-- เซิร์ฟเวอร์ใช้ service_role key ซึ่งข้าม RLS ได้ จึงเป็นทางเดียวที่เข้าถึงข้อมูลได้
alter table users                 enable row level security;
alter table trades                enable row level security;
alter table notification_settings enable row level security;

